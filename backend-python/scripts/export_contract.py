"""
Publish the wire contract the frontend is built against.

WHY THIS EXISTS
`apps/app/src/lib/consult/types.ts` mirrors `src/consult/schema.py` BY HAND. While
both live in one repository that is survivable: they change in one commit and one
review. Once the frontend belongs to another team in another repository, they will
drift -- and the symptom is not a build error. It is a field arriving as
`undefined` in production, on a health product, with nothing failing loudly.

So the Python models -- which are the source of truth -- export what they actually
promise, and the frontend asserts against that file rather than against a comment
telling somebody to remember.

    python scripts/export_contract.py

The output is COMMITTED and ships with the frontend, so the check works in a
repository that contains no Python at all. `tests/test_contract.py` fails if this
file falls behind the models; `contract.test.ts` fails if the TypeScript falls
behind this file. Neither side can move alone.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parents[1]))

from src.consult.schema import (  # noqa: E402
    CONSULTING,
    LEGACY_PHASES,
    Answer,
    ChatTurn,
    ConsultContext,
    ConsultResult,
    IntakePlan,
    Option,
    Question,
)

# Lives HERE, in the repository that owns the models.
#
# It used to be written into apps/app, which worked while the frontend shared this
# repository. It no longer does: the frontend was split out to be owned by another
# team, so the contract has become an interface BETWEEN two repositories rather
# than a file one of them happens to hold.
#
# The frontend keeps its own committed copy and checks the TypeScript against it.
# Updating that copy is therefore a deliberate, visible step in a coordinated
# release -- which is the point. A contract that both sides can change silently is
# not a contract.
OUT = Path(__file__).resolve().parents[2] / "docs" / "consult-contract.json"


def fields(model) -> dict:
    """Field name -> whether it is guaranteed present in a response.

    `required` here means "the frontend may read it without a guard". Pydantic
    defaults make most fields always-present in output even when optional on
    input, which is exactly what a consumer needs to know.
    """
    out = {}
    for name, info in model.model_fields.items():
        out[name] = {
            "required": info.is_required(),
            "always_present_in_output": True,  # model_dump() emits every field
        }
    return out


def literal_values(annotation) -> list:
    import typing

    args = typing.get_args(annotation)
    return [a for a in args if isinstance(a, str)]


def build() -> dict:
    return {
        "_comment": (
            "GENERATED by backend-python/scripts/export_contract.py from the Pydantic "
            "models. Do not edit by hand. This is the contract the frontend is built "
            "against; changing it is a coordinated release for both repositories."
        ),
        "models": {
            "ConsultResult": fields(ConsultResult),
            "ConsultContext": fields(ConsultContext),
            "IntakePlan": fields(IntakePlan),
            "Question": fields(Question),
            "Option": fields(Option),
            "Answer": fields(Answer),
            "ChatTurn": fields(ChatTurn),
        },
        "enums": {
            # The two the frontend branches on. A value added here that the UI does
            # not handle renders as nothing; a value removed breaks a code path.
            "kind": literal_values(ConsultResult.model_fields["kind"].annotation),
            "phase": literal_values(ConsultContext.model_fields["phase"].annotation),
            "question_type": literal_values(Question.model_fields["type"].annotation),
            "question_display": literal_values(Question.model_fields["display"].annotation),
            "chat_role": literal_values(ChatTurn.model_fields["role"].annotation),
        },
        "phase_groups": {
            # Which phases mean "a consultation is open". The frontend uses this to
            # decide `freeText` versus `problem`, and getting it wrong restarts the
            # consultation on every follow-up.
            "consulting": list(CONSULTING),
            "legacy": list(LEGACY_PHASES),
        },
        "source_namespaces": [
            # Chunk.source prefixes. The UI groups by these and must not flatten
            # them: "based on 3 Ayurveda notes" is false when one is the reader's
            # own uploaded report.
            "knowledge",
            "report",
            "graphrag",
            "memory",
        ],
        "request_fields": [
            # What the frontend may send. Read by server.py, not a Pydantic model,
            # so listed explicitly.
            "problem",
            "context",
            "answers",
            "freeText",
            "profile",
            "conversationId",
            "bot_id",
        ],
    }


def main() -> int:
    payload = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current == payload:
        print(f"[contract] already up to date: {OUT.name}")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(payload, encoding="utf-8")
    print(f"[contract] wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
